/**
 * Synchronize generated deployment consumers from the canonical Base manifest.
 * This is safe to run before local builds; promotion runs the equivalent write
 * after it has validated a candidate deployment on-chain.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const canonicalPath = join(root, "contracts", "deployments", "base-8453.json");
const manifest = JSON.parse(await readFile(canonicalPath, "utf8"));

const writeJson = (file) => writeFile(file, JSON.stringify(manifest, null, 2) + "\n");
const generated = () =>
  `// GENERATED by contracts/scripts/promote-manifest.ts. Do not edit.\n` +
  `export const BASE_MAINNET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`;
const browserGenerated =
  `// GENERATED by contracts/scripts/promote-manifest.ts. Do not edit.\n` +
  `export const MANIFEST = ${JSON.stringify(manifest, null, 2)};\n` +
  "export const AZL_TOKEN = MANIFEST.azlToken;\n";

const x402Path = join(root, "agents", "x402-cloud", "bankr.x402.json");
const x402 = JSON.parse(await readFile(x402Path, "utf8"));
for (const service of Object.values(x402.services ?? {})) service.tokenAddress = manifest.external.azl;

await Promise.all([
  writeJson(join(root, "agents", "deployments", "base-8453.json")),
  writeJson(join(root, "api", "lib", "contracts.json")),
  writeFile(join(root, "agents", "x402-cloud", "x402", "manifest.ts"), generated()),
  writeFile(join(root, "launch-skills", "js", "manifest.generated.js"), browserGenerated),
  writeFile(x402Path, JSON.stringify(x402, null, 2) + "\n"),
]);
console.log("[manifest] generated consumers synchronized from contracts/deployments/base-8453.json");
